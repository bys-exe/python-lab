# lab exercise 2 - number operations

no1 = float(input("Enter the 1st number: "))
no2 = float(input("Enter the 2nd number: "))

print("----------RESULTS----------")
print(f"Addition: {no1+no2}")
print(f"Subtraction: {no1-no2}")
print(f"Multiplication: {no1*no2}")
print(f"Division: {no1/no2}")
print(f"Floor Division: {no1//no2}")
print(f"Modulus: {no1%no2}")
print(f"Exponentiation: {no1**no2}")
print("---------------------------")

